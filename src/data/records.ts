export type Format = 'Vinyl' | 'CD' | 'Cassette';

export const formatOptions: Format[] = ['Vinyl', 'CD', 'Cassette'];

export function getFormatPrice(record: VinylRecord, format: Format): number {
  switch (format) {
    case 'CD':
      return 15;
    case 'Cassette':
      return 12;
    default:
      return record.price;
  }
}

export function getMixtapeFormatPrice(format: Format): number {
  switch (format) {
    case 'CD':
      return 15;
    case 'Cassette':
      return 12;
    default:
      return 25;
  }
}
